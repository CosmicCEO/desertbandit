#!/usr/bin/env python3
"""Writes desertbandit/lib/policy.json: the computer player's lookup table, solved exactly by tools/simulate.py.

    python3 tools/gen_policy.py            # rewrites desertbandit/lib/policy.json
    python3 tools/gen_policy.py --check    # exits 1 if the committed file is out of date

R[n][s] is the expected final payout, in $50 units, when the player is forced to roll n free reels with an unbanked stake of s units
(the exact dynamic-programming value from simulate.py). The PHP bot (desertbandit/lib/bot.php) rebuilds the "bank or roll" values from it.
The leading index f is the sweep count (0, 1, 2); only the Sweep Bonus card and Reports Overdue depend on it, so the other cards store f = 0 only.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import simulate as sim   # noqa: E402

OUT = os.path.join(HERE, '..', 'desertbandit', 'lib', 'policy.json')
SMAX = 200                               # stake units tabulated ($10,000); the bot clamps beyond it
KINDS = ['sweep', 'fire', 'offroad', 'subpoena', 'overdue']
USES_F = {'sweep': 3, 'overdue': 3}      # kinds whose value depends on the sweep count


def build():
    cards = {}
    for kind in KINDS:
        card = sim.Card(kind)
        R, D = sim.solve(card)
        nf = USES_F.get(kind, 1)
        table = [[[round(R(n, s, f), 3) for s in range(SMAX + 1)] for n in range(1, 7)] for f in range(nf)]
        cards[kind] = {'ev': round(R(6, 0, 0) * sim.UNIT, 2), 'R': table}
    return {
        'note': 'Generated by tools/gen_policy.py from tools/simulate.py. Do not edit.',
        'unit': sim.UNIT, 'cap': sim.CAP, 'smax': SMAX,
        'params': {
            'sweepBonus': sim.SWEEP_BONUS, 'groundFireMin': sim.GROUND_FIRE_MIN, 'groundFireBonus': sim.GROUND_FIRE_BONUS,
            'offroadMult': sim.OFFROAD_MULT, 'offroadBonus': sim.OFFROAD_BONUS, 'subpoenaSteal': sim.SUBPOENA_STEAL,
            'overdueMult': sim.OVERDUE_MULT, 'overdueBonus': sim.OVERDUE_BONUS,
            'single': {str(k): v for k, v in sim.SINGLE.items()}, 'triple': {str(k): v for k, v in sim.TRIPLE.items()},
            'kindMult': {str(k): v for k, v in sim.KIND_MULT.items()}, 'straight': sim.STRAIGHT,
        },
        'cards': cards,
    }


def main():
    text = json.dumps(build(), separators=(',', ':'), sort_keys=True) + '\n'
    if '--check' in sys.argv:
        have = open(OUT).read() if os.path.exists(OUT) else ''
        if have != text:
            print('desertbandit/lib/policy.json is out of date: run python3 tools/gen_policy.py')
            sys.exit(1)
        print('policy.json is up to date')
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w').write(text)
    print('wrote', os.path.normpath(OUT), '(%d KB)' % (len(text) // 1024))


if __name__ == '__main__':
    main()
